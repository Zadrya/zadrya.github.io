# Tests for scripts/check-attribution.sh and scripts/check-authorship.sh.
set -euo pipefail

scripts="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
failures=0

report() { # <want> <got> <name>
  if [[ "$1" == "$2" ]]; then
    echo "ok: $3"
  else
    echo "FAIL: $3 (wanted $1, got $2)"
    failures=$((failures + 1))
  fi
}

# --- check-attribution.sh: one commit message file ---------------------------

message() { # <want> <name> <message with \n escapes> [--hook]
  local got=accept
  printf '%b\n' "$3" > "$tmp/msg"
  "$scripts/check-attribution.sh" ${4:+"$4"} "$tmp/msg" 2> /dev/null || got=reject
  report "$1" "$got" "message: $2"
}

scissors='# ------------------------ >8 ------------------------'

message accept 'plain conventional commit' 'feat: add a thing\n\nBody text.'
message accept 'subject that mentions CLAUDE.md' 'docs: add CLAUDE.md'
message reject 'co-author trailer' 'feat: add a thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
message reject 'co-author trailer, lower case' 'feat: add a thing\n\nco-authored-by: Someone <someone@example.com>'
message reject 'co-author trailer, space before the colon' 'feat: add a thing\n\nCo-authored-by : Someone <someone@example.com>'
message reject 'assisted-by trailer' 'feat: add a thing\n\nAssisted-by: Claude'
message reject 'sign-off with the Anthropic address' 'feat: add a thing\n\nSigned-off-by: Claude <noreply@anthropic.com>'
message reject 'session trailer' 'feat: add a thing\n\nClaude-Session: https://example.com/session'
message reject 'bare session link' 'feat: add a thing\n\nhttps://claude.ai/code/session_123'
message reject 'generated-with footer' 'feat: add a thing\n\nGenerated with Claude Code'
message reject 'generated-with footer, two spaces' 'feat: add a thing\n\nGenerated with  Claude Code'
message reject 'generated-with footer, bold' 'feat: add a thing\n\nGenerated with **Claude Code**'
message reject 'generated-with footer, markdown link' 'feat: add a thing\n\nGenerated with [Claude Code](https://example.com)'
message reject 'generated-by footer' 'feat: add a thing\n\nGenerated by Claude Code'
message reject 'generated-using footer' 'feat: add a thing\n\nGenerated using Claude Code'
message reject 'written-by footer' 'feat: add a thing\n\nWritten by Claude'
message accept 'hook mode: forbidden text only in the verbose diff' \
  "feat: add a thing\n$scissors\ndiff --git a/file b/file\n+Co-Authored-By: Someone <someone@example.com>" --hook
message reject 'hook mode: trailer below a scissors line with no diff' \
  "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>" --hook
message reject 'hook mode: trailer above the scissors line' \
  "feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>\n$scissors\ndiff --git a/file b/file" --hook
message reject 'stored message: trailer below a scissors line' \
  "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>"

# --- check-authorship.sh: a range of commits in a throwaway repository -------

owner_name='Sklyvan'
owner_email='joangraciataribo@gmail.com'
repo="$tmp/repo"
git init -q -b main "$repo"

commit() { # <author name> <author email> <committer name> <committer email> <message file>
  GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2" GIT_COMMITTER_NAME="$3" GIT_COMMITTER_EMAIL="$4" \
    git -C "$repo" commit -q --allow-empty --no-verify --cleanup=verbatim -F "$5"
}

owner_commit() { # <message with \n escapes>
  printf '%b\n' "$1" > "$tmp/msg"
  commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
}

# Exit codes: 0 passed, 1 a commit was rejected, 2 the range could not be used.
range() { # <wanted exit code> <name> [<range>] [<event name>]
  local got=0
  (cd "$repo" && env GITHUB_EVENT_NAME="${4:-}" "$scripts/check-authorship.sh" "${3:-base..HEAD}" > /dev/null 2>&1) || got=$?
  report "$1" "$got" "range: $2"
  git -C "$repo" reset -q --hard base
}

owner_commit 'chore: base'
git -C "$repo" tag base

owner_commit 'feat: add a thing'
owner_commit 'fix: repair a thing'
range 0 'two clean commits by the owner'

{
  printf 'feat: add a thing\n\n'
  for _ in $(seq 1 4000); do
    printf 'This filler line makes the message far larger than a pipe buffer.\n'
  done
} > "$tmp/msg"
commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 0 'clean commit with a very long message'

printf 'feat: add a thing\n' > "$tmp/msg"
commit 'Claude' 'noreply@anthropic.com' "$owner_name" "$owner_email" "$tmp/msg"
range 1 'foreign author'

commit 'Claude' "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 1 'foreign author name with the owner email'

commit "$owner_name" 'someone@example.com' "$owner_name" "$owner_email" "$tmp/msg"
range 1 'owner name with a foreign author email'

commit "$owner_name" "$owner_email" 'GitHub' 'noreply@github.com' "$tmp/msg"
range 1 'foreign committer'

commit "$owner_name" "$owner_email" 'GitHub' "$owner_email" "$tmp/msg"
range 1 'foreign committer name with the owner email'

owner_commit 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>'
range 1 'co-author trailer'

owner_commit 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>'
owner_commit 'fix: a clean commit on top'
range 1 'co-author trailer in an older commit of the range'

owner_commit "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>"
range 1 'co-author trailer below a scissors line'

{
  printf 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>\n\n'
  for _ in $(seq 1 4000); do
    printf 'This filler line makes the message far larger than a pipe buffer.\n'
  done
} > "$tmp/msg"
commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 1 'co-author trailer in a very long message'

owner_commit "feat: add a thing $(printf '\xe2\x80\x94') with an em dash"
range 1 'em dash in the message'

owner_commit 'feat: add a thing'
range 2 'base that does not exist' 'no-such-ref..HEAD'

owner_commit 'feat: add a thing'
range 2 'argument that is not a range' 'HEAD'

range 0 'empty range outside a pull request' 'base..base'
range 1 'empty range on a pull request' 'base..base' 'pull_request'

if [[ "$failures" -ne 0 ]]; then
  echo "$failures test(s) failed"
  exit 1
fi
echo "all hook tests passed"
