#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Tests for scripts/check-attribution.sh, scripts/check-authorship.sh and the
# pre-push hook (scripts/pre-push.sh through .lefthook/pre-push/).
set -euo pipefail

# Git exports GIT_DIR, GIT_INDEX_FILE and friends to hooks. This script runs
# from the pre-commit hook and creates a throwaway repository: with those
# variables set, its git commands would act on the real repository instead
# (this happened in a linked worktree). Clear them before anything else.
# The list is assigned first so that a failing `git rev-parse` aborts the script.
local_git_vars="$(git rev-parse --local-env-vars)"
# shellcheck disable=SC2086
unset $local_git_vars
for name in $local_git_vars; do
  if [[ -n "${!name+set}" ]]; then
    echo "error: $name is still set, refusing to create a throwaway repository" >&2
    exit 2
  fi
done

scripts="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
failures=0

report() { # <want> <got> <name>
  if [[ "$1" == "$2" ]]; then
    echo "ok: $3"
  else
    echo "FAIL: $3 (wanted $1, got $2)"
    failures=$((failures + 1))
  fi
}

# --- check-attribution.sh: one commit message file ---------------------------

message() { # <want> <name> <message with \n escapes> [--hook]
  local got=accept
  printf '%b\n' "$3" > "$tmp/msg"
  "$scripts/check-attribution.sh" ${4:+"$4"} "$tmp/msg" 2> /dev/null || got=reject
  report "$1" "$got" "message: $2"
}

scissors='# ------------------------ >8 ------------------------'

message accept 'plain conventional commit' 'feat: add a thing\n\nBody text.'
message accept 'subject that mentions CLAUDE.md' 'docs: add CLAUDE.md'
message reject 'co-author trailer' 'feat: add a thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
message reject 'co-author trailer, lower case' 'feat: add a thing\n\nco-authored-by: Someone <someone@example.com>'
message reject 'co-author trailer, space before the colon' 'feat: add a thing\n\nCo-authored-by : Someone <someone@example.com>'
message reject 'assisted-by trailer' 'feat: add a thing\n\nAssisted-by: Claude'
message reject 'sign-off with the Anthropic address' 'feat: add a thing\n\nSigned-off-by: Claude <noreply@anthropic.com>'
message reject 'session trailer' 'feat: add a thing\n\nClaude-Session: https://example.com/session'
message reject 'bare session link' 'feat: add a thing\n\nhttps://claude.ai/code/session_123'
message reject 'generated-with footer' 'feat: add a thing\n\nGenerated with Claude Code'
message reject 'generated-with footer, two spaces' 'feat: add a thing\n\nGenerated with  Claude Code'
message reject 'generated-with footer, bold' 'feat: add a thing\n\nGenerated with **Claude Code**'
message reject 'generated-with footer, markdown link' 'feat: add a thing\n\nGenerated with [Claude Code](https://example.com)'
message reject 'generated-by footer' 'feat: add a thing\n\nGenerated by Claude Code'
message reject 'generated-using footer' 'feat: add a thing\n\nGenerated using Claude Code'
message reject 'written-by footer' 'feat: add a thing\n\nWritten by Claude'
message accept 'hook mode: forbidden text only in the verbose diff' \
  "feat: add a thing\n$scissors\ndiff --git a/file b/file\n+Co-Authored-By: Someone <someone@example.com>" --hook
message reject 'hook mode: trailer below a scissors line with no diff' \
  "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>" --hook
message reject 'hook mode: trailer above the scissors line' \
  "feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>\n$scissors\ndiff --git a/file b/file" --hook
message reject 'stored message: trailer below a scissors line' \
  "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>"

# --- check-authorship.sh: a range of commits in a throwaway repository -------

owner_name='Sklyvan'
owner_email='joangraciataribo@gmail.com'
repo="$tmp/repo"
git init -q -b main "$repo"

# Refuse to continue unless every git command below acts on the throwaway
# repository and nothing else.
if [[ "$(cd "$repo" && git rev-parse --absolute-git-dir)" != "$(cd "$repo" && pwd -P)/.git" ]]; then
  echo "error: the throwaway repository is not isolated from the real one" >&2
  exit 2
fi

commit() { # <author name> <author email> <committer name> <committer email> <message file>
  GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2" GIT_COMMITTER_NAME="$3" GIT_COMMITTER_EMAIL="$4" \
    git -C "$repo" commit -q --allow-empty --no-verify --cleanup=verbatim -F "$5"
}

owner_commit() { # <message with \n escapes>
  printf '%b\n' "$1" > "$tmp/msg"
  commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
}

# Exit codes: 0 passed, 1 a commit was rejected, 2 the range could not be used.
range() { # <wanted exit code> <name> [<range>] [<event name>]
  local got=0
  (cd "$repo" && env GITHUB_EVENT_NAME="${4:-}" "$scripts/check-authorship.sh" "${3:-base..HEAD}" > /dev/null 2>&1) || got=$?
  report "$1" "$got" "range: $2"
  git -C "$repo" reset -q --hard base
}

owner_commit 'chore: base'
git -C "$repo" tag base

owner_commit 'feat: add a thing'
owner_commit 'fix: repair a thing'
range 0 'two clean commits by the owner'

{
  printf 'feat: add a thing\n\n'
  for _ in $(seq 1 4000); do
    printf 'This filler line makes the message far larger than a pipe buffer.\n'
  done
} > "$tmp/msg"
commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 0 'clean commit with a very long message'

printf 'feat: add a thing\n' > "$tmp/msg"
commit 'Claude' 'noreply@anthropic.com' "$owner_name" "$owner_email" "$tmp/msg"
range 1 'foreign author'

commit 'Claude' "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 1 'foreign author name with the owner email'

commit "$owner_name" 'someone@example.com' "$owner_name" "$owner_email" "$tmp/msg"
range 1 'owner name with a foreign author email'

commit "$owner_name" "$owner_email" 'GitHub' 'noreply@github.com' "$tmp/msg"
range 1 'foreign committer'

commit "$owner_name" "$owner_email" 'GitHub' "$owner_email" "$tmp/msg"
range 1 'foreign committer name with the owner email'

owner_commit 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>'
range 1 'co-author trailer'

owner_commit 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>'
owner_commit 'fix: a clean commit on top'
range 1 'co-author trailer in an older commit of the range'

owner_commit "feat: add a thing\n\n$scissors\nCo-Authored-By: Someone <someone@example.com>"
range 1 'co-author trailer below a scissors line'

{
  printf 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>\n\n'
  for _ in $(seq 1 4000); do
    printf 'This filler line makes the message far larger than a pipe buffer.\n'
  done
} > "$tmp/msg"
commit "$owner_name" "$owner_email" "$owner_name" "$owner_email" "$tmp/msg"
range 1 'co-author trailer in a very long message'

owner_commit "feat: add a thing $(printf '\xe2\x80\x94') with an em dash"
range 1 'em dash in the message'

owner_commit 'feat: add a thing'
range 2 'base that does not exist' 'no-such-ref..HEAD'

owner_commit 'feat: add a thing'
range 2 'argument that is not a range' 'HEAD'

range 0 'empty range outside a pull request' 'base..base'
range 1 'empty range on a pull request' 'base..base' 'pull_request'

# --- check-authorship.sh: replace refs are ignored ---------------------------

disguise() { # <commit> <name> <email>: a copy of <commit> with another author and committer
  GIT_AUTHOR_NAME="$2" GIT_AUTHOR_EMAIL="$3" GIT_COMMITTER_NAME="$2" GIT_COMMITTER_EMAIL="$3" \
    git -C "$repo" commit-tree -p "$1^" -F "$tmp/msg" "$1^{tree}"
}

printf 'feat: add a thing\n' > "$tmp/msg"
commit 'Claude' 'noreply@anthropic.com' 'Claude' 'noreply@anthropic.com' "$tmp/msg"
foreign="$(git -C "$repo" rev-parse HEAD)"
git -C "$repo" replace "$foreign" "$(disguise "$foreign" "$owner_name" "$owner_email")"
report "$owner_name" "$(git -C "$repo" log -1 --format=%an HEAD)" 'replace ref: git log shows the disguise'
range 1 'foreign commit disguised as the owner by a replace ref'
git -C "$repo" replace -d "$foreign" > /dev/null

owner_commit 'feat: add a thing'
clean="$(git -C "$repo" rev-parse HEAD)"
git -C "$repo" replace "$clean" "$(disguise "$clean" 'Claude' 'noreply@anthropic.com')"
range 0 'owner commit replaced by a foreign one'
git -C "$repo" replace -d "$clean" > /dev/null

# --- pre-push hook: real pushes to a throwaway remote ------------------------

# git itself writes the refs to the hook's standard input, so new branches,
# updates and deletions arrive exactly as they do in a real clone.
remote="$tmp/remote.git"
work="$tmp/work"
git init -q --bare -b main "$remote"
# Without this the remote itself refuses to delete main, and the test of the
# hook would pass whatever the hook does.
git -C "$remote" config receive.denyDeleteCurrent ignore
git init -q -b main "$work"
if [[ "$(cd "$remote" && git rev-parse --absolute-git-dir)" != "$(cd "$remote" && pwd -P)" ||
  "$(cd "$work" && git rev-parse --absolute-git-dir)" != "$(cd "$work" && pwd -P)/.git" ]]; then
  echo "error: the throwaway remote or clone is not isolated from the real one" >&2
  exit 2
fi

# The hook runs the copies, which are the scripts under test.
cp -R "$scripts" "$work/scripts"
mkdir -p "$work/.lefthook"
cp -R "$scripts/../.lefthook/pre-push" "$work/.lefthook/pre-push"
mkdir "$tmp/hooks"
cat > "$tmp/hooks/pre-push" << EOF
#!/usr/bin/env bash
exec "$work/.lefthook/pre-push/protect-main-and-authorship.sh"
EOF
chmod +x "$tmp/hooks/pre-push"
git -C "$work" config core.hooksPath "$tmp/hooks"
git -C "$work" remote add origin "$remote"

repo="$work" # the commit helpers above now act on the clone
owner_commit 'chore: base'
git -C "$work" push -q --no-verify origin main 2> /dev/null

pushes() { # <accept|reject> <name> <git push arguments...>
  local want="$1" name="$2" got=accept
  shift 2
  git -C "$work" push -q origin "$@" > /dev/null 2>&1 || got=reject
  report "$want" "$got" "pre-push: $name"
}

on_remote() { # <branch>: prints the branch head on the remote, or "none"
  git -C "$remote" rev-parse --verify --quiet "refs/heads/$1" || echo none
}

main_head="$(on_remote main)"

git -C "$work" switch -q -c clean main
echo change > "$work/file.txt"
git -C "$work" add file.txt
owner_commit 'feat: add a file'
pushes accept 'clean new branch (zero remote SHA)' clean
owner_commit 'fix: an empty commit on top'
pushes accept 'clean update of an existing branch' clean

git -C "$work" switch -q -c foreign main
printf 'feat: add a thing\n' > "$tmp/msg"
commit 'Claude' 'noreply@anthropic.com' "$owner_name" "$owner_email" "$tmp/msg"
pushes reject 'empty commit with a foreign author' foreign
report none "$(on_remote foreign)" 'pre-push: the refused branch is not on the remote'

git -C "$work" switch -q -c committer main
echo change > "$work/other.txt"
git -C "$work" add other.txt
commit "$owner_name" "$owner_email" 'GitHub' 'noreply@github.com' "$tmp/msg"
pushes reject 'commit with changes and a foreign committer' committer

git -C "$work" switch -q -c attributed main
owner_commit 'feat: add a thing\n\nCo-Authored-By: Someone <someone@example.com>'
pushes reject 'commit with an attribution line' attributed

git -C "$work" switch -q -c session main
owner_commit 'feat: add a thing\n\nClaude-Session: https://example.com/session'
owner_commit 'fix: a clean commit on top'
pushes reject 'attribution line below a clean commit' session

# git leaves up-to-date refs off the hook input: push a new clean branch.
git -C "$work" switch -q -c second clean
owner_commit 'feat: add another thing'
pushes reject 'two branches, the foreign one first' foreign second
pushes reject 'two branches, the foreign one last' second foreign
report none "$(on_remote second)" 'pre-push: no branch of a refused push is on the remote'

main_case() { # <name> <git push arguments...>: main must stay where it was
  pushes reject "$@"
  report "$main_head" "$(on_remote main)" "pre-push: main is unchanged after: $1"
  git -C "$remote" update-ref refs/heads/main "$main_head"
}

git -C "$work" switch -q main
owner_commit 'feat: add a thing'
main_case 'push to main' main
main_case 'push of a clean feature branch to main' clean:main
main_case 'deletion of main' --delete main

pushes accept 'deletion of a branch (zero local SHA)' --delete clean
report none "$(on_remote clean)" 'pre-push: the deleted branch is gone from the remote'

if [[ "$failures" -ne 0 ]]; then
  echo "$failures test(s) failed"
  exit 1
fi
echo "all hook tests passed"
